    # --- WriterResult (Requirement 3.3 — included for completeness) ---

    @settings(max_examples=100)
    @given(
        sha256=sha256_hashes,
        file_size=st.integers(min_value=0, max_value=10**9),
        diagnostics=st.lists(non_empty_text, max_size=10),
    )
    def test_writer_result_preserves_fields(
        self,
        sha256: str,
        file_size: int,
        diagnostics: list[str],
    ) -> None:
        """WriterResult preserves all fields exactly as provided."""
        output_path = Path("/tmp/test.json")
        fmt = OutputFormat.SPDX_2_3
        result = WriterResult(
            output_path=output_path,
            format=fmt,
            sha256=sha256,
            file_size=file_size,
            diagnostics=diagnostics,
        )
        assert result.output_path == output_path
        assert result.format == fmt
        assert result.sha256 == sha256
        assert result.file_size == file_size
        assert result.diagnostics == diagnostics
