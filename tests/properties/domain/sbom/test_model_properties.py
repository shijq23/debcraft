    # --- SBOMCreationInfo (Requirement 1.5) ---

    @settings(max_examples=100)
    @given(info=sbom_creation_infos())
    def test_creation_info_preserves_fields(self, info: SBOMCreationInfo) -> None:
        """SBOMCreationInfo preserves tools, created, creators, license_list_version."""
        assert len(info.tools) >= 1
        assert all(t.startswith("Tool: ") for t in info.tools)
        assert len(info.creators) >= 1
