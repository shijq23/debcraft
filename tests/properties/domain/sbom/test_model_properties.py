"""Property-based tests for SBOM domain model construction.

# Feature: sbom-writers, Property 1: Model construction preserves valid inputs

**Validates: Requirements 1.2, 1.3, 1.4, 1.5, 1.6, 1.7, 1.8**

Property 1: Model construction preserves valid inputs.
For any set of field values that conform to the stated constraints (non-empty
strings where required, SPDX ID pattern SPDXRef-[a-zA-Z0-9.-]+, hash lengths
matching algorithms, license ID pattern LicenseRef-[a-zA-Z0-9.-]+),
constructing an SBOM value object SHALL succeed and all fields SHALL be
accessible with the exact values provided.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from hypothesis import given, settings
from hypothesis import strategies as st

from debcraft.domain.sbom.values import (
    ChecksumAlgorithm,
    ExternalReferenceCategory,
    OutputFormat,
    RelationshipType,
    SBOMChecksum,
    SBOMCreationInfo,
    SBOMDocument,
    SBOMExternalReference,
    SBOMExtractedLicense,
    SBOMPackage,
    SBOMRelationship,
    WriterResult,
)

from .strategies import (
    md5_hashes,
    non_empty_text,
    sbom_checksums,
    sbom_creation_infos,
    sbom_documents,
    sbom_external_references,
    sbom_extracted_licenses,
    sbom_packages,
    sbom_relationships,
    sha1_hashes,
    sha256_hashes,
)

# ---------------------------------------------------------------------------
# Property 1: Model construction preserves valid inputs
# ---------------------------------------------------------------------------


@pytest.mark.unit
@pytest.mark.spdx
class TestProperty1ModelConstructionPreservesValidInputs:
    """Property 1: Model construction preserves valid inputs.

    For any valid inputs conforming to the stated constraints, constructing
    an SBOM value object SHALL succeed and all fields SHALL be accessible
    with the exact values provided.
    """

    # --- SBOMChecksum (Requirement 1.6) ---

    @settings(max_examples=100)
    @given(value=sha256_hashes)
    def test_checksum_sha256_preserves_fields(self, value: str) -> None:
        """SBOMChecksum with SHA256 preserves algorithm and value."""
        checksum = SBOMChecksum(algorithm=ChecksumAlgorithm.SHA256, value=value)
        assert checksum.algorithm == ChecksumAlgorithm.SHA256
        assert checksum.value == value

    @settings(max_examples=100)
    @given(value=sha1_hashes)
    def test_checksum_sha1_preserves_fields(self, value: str) -> None:
        """SBOMChecksum with SHA1 preserves algorithm and value."""
        checksum = SBOMChecksum(algorithm=ChecksumAlgorithm.SHA1, value=value)
        assert checksum.algorithm == ChecksumAlgorithm.SHA1
        assert checksum.value == value

    @settings(max_examples=100)
    @given(value=md5_hashes)
    def test_checksum_md5_preserves_fields(self, value: str) -> None:
        """SBOMChecksum with MD5 preserves algorithm and value."""
        checksum = SBOMChecksum(algorithm=ChecksumAlgorithm.MD5, value=value)
        assert checksum.algorithm == ChecksumAlgorithm.MD5
        assert checksum.value == value

    @settings(max_examples=100)
    @given(checksum=sbom_checksums())
    def test_checksum_composite_preserves_fields(self, checksum: SBOMChecksum) -> None:
        """SBOMChecksum generated by composite strategy preserves all fields."""
        reconstructed = SBOMChecksum(algorithm=checksum.algorithm, value=checksum.value)
        assert reconstructed.algorithm == checksum.algorithm
        assert reconstructed.value == checksum.value

