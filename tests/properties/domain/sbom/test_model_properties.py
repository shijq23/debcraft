        reconstructed = SBOMCreationInfo(
            tools=info.tools,
            created=info.created,
            creators=info.creators,
            license_list_version=info.license_list_version,
        )
        assert reconstructed.tools == info.tools
        assert reconstructed.created == info.created
        assert reconstructed.creators == info.creators
        assert reconstructed.license_list_version == info.license_list_version

